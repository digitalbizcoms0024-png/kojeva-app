// Generates deterministic SAMPLE data (not real Kojeva numbers) as SQL on stdout.
// Usage: node scripts/gen-sample.ts > seed/sample.sql
import { attributePod, type AttributionAd } from "../shared/attribution.ts";
import { buildConcepts, type ConceptAd } from "../shared/concepts.ts";
import { parseAdName } from "../shared/naming.ts";
import { GROUPS, PODS } from "../shared/taxonomy.ts";

const DAYS = 90;

function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261016);
const between = (a: number, b: number) => a + rand() * (b - a);
const pick = <T,>(xs: readonly T[]): T => xs[Math.floor(rand() * xs.length)]!;
const q = (s: string | null) => (s == null ? "NULL" : `'${s.replace(/'/g, "''")}'`);

function isoDay(offset: number): string {
  const d = new Date();
  d.setUTCHours(0, 0, 0, 0);
  d.setUTCDate(d.getUTCDate() - offset);
  return d.toISOString().slice(0, 10);
}

const LEGACY_NAMES = [
  "Video 153", "Video 131", "Video 88", "4-2", "V457 | CBO", "Video 100 | PDP", "batch15-2",
  "HxM-120 Proving My Husband Wrong - Ad", "23v2", "HxM 7.1 Funeral_MatureFace_UGC_Story",
  "V556 PDP", "Video 30", "Video 22", "Video 61", "V402", "batch12-1", "batch14-3", "HxM-98 Wedding Day",
  "7-1", "18v3", "Video 140 | PDP", "V488 | CBO", "Video 12", "HxM 5.2 Gua Sha Broke", "V511",
  "batch16-1", "Video 77", "V530 PDP", "31v1", "HxM2-Yapper Founder-2 | Post ID",
  "HxM-1-ANIMSONG-Husband at Walmart | Post ID", "kojeva 10 HK2 | Post ID",
  "GS_SA_COMPARISON VSL_HARRIS-h2 | Post ID", "Copy of 22v1",
];
const ANGLES = ["Depuff", "MatureFace", "Comparison", "SocialProof", "Husband", "Jawline"];
const FORMATS = ["UGC", "UGC", "UGC", "Static", "VSL", "Interview"];
const HOOKS = ["Story", "Curiosity", "Contrarian", "Problem", "Shock", "Benefit"];
const LPS = ["PDP", "PDP", "LIST", "ADV"];
const CAMPAIGNS = [
  { id: "c_abo", name: "ABO | Creative Testing" },
  { id: "c_cc", name: "Cost Cap | Scale" },
  { id: "c_bc", name: "Bid Cap | Graveyard" },
  { id: "c_cbo", name: "CBO | Broad" },
];

const editors = PODS.flatMap((p, i) => [
  { id: `ed_${p.id}_1`, name: `Editor ${String.fromCharCode(65 + i)}1`, pod: p.id },
  { id: `ed_${p.id}_2`, name: `Editor ${String.fromCharCode(65 + i)}2`, pod: p.id },
]);

const out: string[] = [
  "-- SAMPLE DATA generated by scripts/gen-sample.ts. Not real Kojeva performance.",
  "DELETE FROM ad_daily; DELETE FROM assignments; DELETE FROM ads; DELETE FROM posts; DELETE FROM editors; DELETE FROM sync_runs; DELETE FROM tw_daily; DELETE FROM tw_days;",
];
for (const e of editors)
  out.push(`INSERT INTO editors (id, name, pod_id) VALUES (${q(e.id)}, ${q(e.name)}, ${q(e.pod)});`);

const conceptAds: ConceptAd[] = [];

interface PostPlan { id: string; name: string; launch: number; life: number; cpa: number; scale: number }
const posts: PostPlan[] = [];

let creative = 600;
for (let i = 0; i < 64; i++) {
  const legacy = i < LEGACY_NAMES.length;
  const hinted = legacy ? parseAdName(LEGACY_NAMES[i]!).strategistHint : null;
  const pod = hinted ? PODS.find((p) => p.code === hinted)! : pick(PODS);
  const name = legacy
    ? LEGACY_NAMES[i]!
    : `${pod.code}-V${creative++}${rand() < 0.4 ? `-i${1 + Math.floor(rand() * 3)}` : ""} | ${pick(ANGLES)} | ${pick(FORMATS)} | ${pick(HOOKS)} | ${pick(LPS)}`;
  const launch = legacy ? Math.floor(between(20, DAYS - 1)) : Math.floor(between(0, 45));
  const winner = rand() < 0.25;
  const plan: PostPlan = {
    id: `post_${1000 + i}`,
    name,
    launch,
    life: Math.min(launch + 1, Math.floor(between(4, 70))),
    cpa: winner ? between(9, 14) : between(14, 36),
    scale: winner ? between(150, 900) : between(25, 140),
  };
  posts.push(plan);

  const parsed = parseAdName(name);
  const mediaType = parsed.format === "Static" ? "image" : "video";
  out.push(`INSERT INTO posts (id, media_type, created_time) VALUES (${q(plan.id)}, ${q(mediaType)}, ${q(isoDay(launch))});`);

  // Winners get copied into scaling campaigns, like real account structure.
  const copies = winner ? 2 + Math.floor(rand() * 7) : rand() < 0.3 ? 2 : 1;
  // Like the real account: testing ad sets carry the strategist's name; a few don't.
  const testAdSet = legacy
    ? `${pick(["ME", "QW", "TV", "YD"])} | R${1 + (i % 5)}-S${10 + i} | ${rand() < 0.5 ? "Statics" : "Videos"}`
    : rand() < 0.85
      ? `IH | ${pod.name} | KOJEVA ${1 + (i % 9)}`
      : "Top Spenders From ABO";
  const adsForAttribution: AttributionAd[] = [];
  for (let c = 0; c < copies; c++) {
    const camp = c === 0 ? CAMPAIGNS[0]! : pick(CAMPAIGNS.slice(1));
    const adId = `${plan.id.replace("post", "ad")}_${c}`;
    const adName = c === 0 ? name : `${name} - Copy${c > 1 ? ` ${c}` : ""}`;
    const adsetName = c === 0 ? testAdSet : `${camp.name.split(" |")[0]} | Scale ${c}`;
    const adsetId = `as_${adsetName.replace(/[^A-Za-z0-9]+/g, "_")}`;
    conceptAds.push({ id: `${plan.id.replace("post", "ad")}_${c}`, name: c === 0 ? name : `${name} - Copy`, adsetId, adsetName });
    const createdDay = plan.launch - (c === 0 ? 0 : Math.min(plan.launch, Math.floor(between(3, 8))));
    adsForAttribution.push({ name: adName, adsetName, createdTime: isoDay(createdDay) });
    const alive = plan.launch - plan.life;
    const status = alive <= 0 && (winner || rand() < 0.5) ? "ACTIVE" : "PAUSED";
    out.push(
      `INSERT INTO ads (id, post_id, name, campaign_id, campaign_name, adset_id, adset_name, status, created_time) VALUES (` +
        [q(adId), q(plan.id), q(adName), q(camp.id), q(camp.name), q(adsetId), q(adsetName), q(status), q(isoDay(createdDay))].join(", ") + ");",
    );

    const rows: string[] = [];
    const twRows: string[] = [];
    const start = createdDay;
    for (let day = start; day > Math.max(-1, plan.launch - plan.life) && day >= 0; day--) {
      const age = plan.launch - day;
      const fatigue = 1 + Math.max(0, age - 21) * 0.015;
      const spend = plan.scale * (c === 0 ? 1 : 1.6) * Math.min(1, (age + 1) / 4) * between(0.6, 1.4);
      const dayCpa = plan.cpa * fatigue * between(0.7, 1.35);
      const purchases = Math.max(0, Math.round(spend / dayCpa + between(-0.5, 0.5)));
      const revenue = purchases * between(20, 29); // ~$24 AOV, matching $14 CPA ↔ 1.7 ROAS
      const impressions = Math.round((spend / between(14, 24)) * 1000);
      const clicks = Math.round(impressions * between(0.012, 0.055));
      rows.push(`(${q(adId)}, ${q(isoDay(day))}, ${Math.round(spend * 100)}, ${impressions}, ${clicks}, ${purchases}, ${Math.round(revenue * 100)})`);
      // Triple Whale's pixel usually credits somewhat fewer orders than Meta. Derived without rand()
      // so the rest of the sample stays the same.
      const twShare = 0.7 + ((day * 7 + c * 3) % 9) / 30;
      if (purchases > 0) twRows.push(`(${q(adId)}, ${q(isoDay(day))}, ${Math.round(purchases * twShare * 1000)}, ${Math.round(revenue * twShare * 100)})`);
    }
    if (twRows.length) out.push(`INSERT INTO tw_daily (ad_id, date, orders_milli, revenue_cents) VALUES\n${twRows.join(",\n")};`);
    if (rows.length)
      out.push(`INSERT INTO ad_daily (ad_id, date, spend_cents, impressions, link_clicks, purchases, revenue_cents) VALUES\n${rows.join(",\n")};`);
  }

  // Same rules the live sync will use; about a third of the rest were tagged by hand.
  const auto = attributePod(adsForAttribution);
  const manual = !auto && rand() < 0.35;
  const podId = auto ? GROUPS.find((p) => p.code === auto.podCode)!.id : manual ? pod.id : null;
  if (podId || parsed.angle || parsed.format) {
    const podEditors = editors.filter((e) => e.pod === podId);
    const editor = podEditors.length ? pick(podEditors) : null;
    out.push(
      `INSERT INTO assignments (post_id, pod_id, pod_source, editor_id, angle, format, hook, landing_page, tags_source, updated_at, updated_by) VALUES (` +
        [q(plan.id), q(podId), q(auto ? auto.source : manual ? "manual" : null), q(editor?.id ?? null),
         q(parsed.angle), q(parsed.format), q(parsed.hook), q(parsed.landingPage), q("name"), q(isoDay(0)), q("sample")].join(", ") + ");",
    );
  }
}

for (const c of buildConcepts(conceptAds)) {
  out.push(
    `INSERT INTO concepts (id, adset_id, adset_name, label, pod_id) VALUES (${[c.id, c.adsetId, c.adsetName, c.label].map(q).join(", ")}, ${q(GROUPS.find((g) => g.code === c.podCode)!.id)});`,
    `UPDATE ads SET concept_id = ${q(c.id)} WHERE id IN (${c.adIds.map(q).join(", ")});`,
  );
}

const now = new Date().toISOString();
out.push(`INSERT INTO tw_days (date, model, synced_at) SELECT DISTINCT date, 'Clicks & Views', ${q(now)} FROM ad_daily;`);
out.push(`INSERT INTO sync_runs (source, started_at, finished_at, status, message) VALUES ('sample', ${q(now)}, ${q(now)}, 'ok', 'Sample data loaded');`);
console.log(out.join("\n"));
